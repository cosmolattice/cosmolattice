/* Researcher map (publications/Researcher-map.html).

   Renders an equirectangular world map of where the CosmoLattice "Using CL"
   researchers are based. Mounts on a single marker placed in the page:

     <div class="cl-map-mount"
          data-locations="researcher-locations.json"
          data-world="world-lowres.json"
          data-back="Publications.html"></div>

   The data and geometry arrive as page-local <script src> globals
   (window.CL_MAP_DATA, window.CL_MAP_WORLD) — see researcher-locations.js
   (generated by scripts/build_map_data.py) and world-lowres.js (static asset).
   Using scripts rather than fetch() means the page works over file:// as well as
   http (fetch of a local file is blocked by the browser). A fetch fallback
   remains for anyone who wires the mount with data-locations/data-world instead.
   Styling lives in extra.css under .cl-map. Progressive enhancement: no mount → no-op.

   Projection (matches build of world-lowres.json): native space is 1200×600,
   x = (lon+180)/360·1200, y = (90−lat)/180·600. The <svg> viewBox crops the
   empty polar bands. */
(function () {
  "use strict";

  var NS = "http://www.w3.org/2000/svg";
  var VB_W = 1200, VB_H = 600;
  function proj(lat, lon) { return [(lon + 180) / 360 * VB_W, (90 - lat) / 180 * VB_H]; }

  function el(tag, cls) { var e = document.createElement(tag); if (cls) e.className = cls; return e; }
  function svgEl(tag, cls) { var e = document.createElementNS(NS, tag); if (cls) e.setAttribute("class", cls); return e; }
  function esc(s) { var d = document.createElement("div"); d.textContent = s == null ? "" : s; return d.innerHTML; }

  /* Paper titles come from INSPIRE with the odd bit of inline LaTeX. MathJax
     does not run over nodes this file builds, so render the few constructs that
     actually occur (\(α\), Z_2) as plain Unicode and drop the rest. */
  var GREEK = {
    alpha: "α", beta: "β", gamma: "γ", delta: "δ", epsilon: "ε", zeta: "ζ", eta: "η",
    theta: "θ", kappa: "κ", lambda: "λ", mu: "μ", nu: "ν", xi: "ξ", pi: "π", rho: "ρ",
    sigma: "σ", tau: "τ", phi: "φ", chi: "χ", psi: "ψ", omega: "ω",
    Gamma: "Γ", Delta: "Δ", Theta: "Θ", Lambda: "Λ", Xi: "Ξ", Pi: "Π", Sigma: "Σ",
    Phi: "Φ", Psi: "Ψ", Omega: "Ω", times: "×", pm: "±", to: "→", ell: "ℓ", infty: "∞"
  };
  var SUB = { 0: "₀", 1: "₁", 2: "₂", 3: "₃", 4: "₄", 5: "₅", 6: "₆", 7: "₇", 8: "₈", 9: "₉" };
  var SUP = { 0: "⁰", 1: "¹", 2: "²", 3: "³", 4: "⁴", 5: "⁵", 6: "⁶", 7: "⁷", 8: "⁸", 9: "⁹" };
  function demath(s) {
    return String(s == null ? "" : s)
      .replace(/\\[()[\]]|\$+/g, "")                          // math delimiters
      .replace(/\\([A-Za-z]+)\s*/g, function (m, w) { return GREEK[w] || ""; })
      .replace(/([_^])\{?([0-9])\}?/g, function (m, k, d) { return (k === "_" ? SUB : SUP)[d]; })
      .replace(/[{}]/g, "")
      .replace(/\s+/g, " ").trim();
  }

  function hex(h) { return [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)]; }
  function mix(c1, c2, t) {
    var a = hex(c1), b = hex(c2), r = function (i) { return Math.round(a[i] + (b[i] - a[i]) * t); };
    return "rgb(" + r(0) + "," + r(1) + "," + r(2) + ")";
  }

  /* ---- continents (for the tab-like map switcher) ----
     Each city is bucketed into a continent to drive the "World / Europe / …"
     tabs. ISO country → continent covers the current data; contFallback keeps
     it robust to new countries. Only the map (viewBox + which markers show)
     changes per tab — the "Leading hubs" list stays global by design. */
  var CONTS = [
    { key: "eu", name: "Europe" }, { key: "as", name: "Asia" },
    { key: "na", name: "N. America" }, { key: "sa", name: "S. America" },
    { key: "oc", name: "Oceania" }, { key: "af", name: "Africa" }
  ];
  var C2C = {
    FR: "eu", ES: "eu", CH: "eu", DE: "eu", PL: "eu", BE: "eu", FI: "eu", GB: "eu",
    PT: "eu", IT: "eu", CZ: "eu", RU: "eu", TR: "eu", NL: "eu", SE: "eu", AT: "eu",
    DK: "eu", NO: "eu", IE: "eu", GR: "eu", HU: "eu", RO: "eu",
    CN: "as", JP: "as", IN: "as", KR: "as", IL: "as", KZ: "as", AE: "as", SG: "as",
    TW: "as", HK: "as", TH: "as", SA: "as", IR: "as",
    US: "na", MX: "na", CA: "na",
    BR: "sa", AR: "sa", CL: "sa", CO: "sa", PE: "sa", UY: "sa",
    AU: "oc", NZ: "oc",
    ZA: "af", EG: "af", NG: "af", MA: "af", KE: "af"
  };
  function contFallback(lat, lon) {
    if (lon < -30) return lat > 13 ? "na" : "sa";
    if (lon > 100) return lat < -10 ? "oc" : "as";
    if (lat < 12) return "af";
    if (lon > 45) return "as";
    return "eu";
  }
  function continentOf(c) { return C2C[c.country] || contFallback(c.lat, c.lon); }

  /* Frame a set of cities: bounding box of their projected points, padded, then
     forced to the world view's aspect ratio and clamped to the map so the frame
     keeps a constant height as you switch tabs. Returns [x, y, w, h]. */
  function computeVB(list, tighten) {
    var AR = 1005 / 412, xs = [], ys = [];
    list.forEach(function (c) { var p = proj(c.lat, c.lon); xs.push(p[0]); ys.push(p[1]); });
    var minx = Math.min.apply(null, xs), maxx = Math.max.apply(null, xs);
    var miny = Math.min.apply(null, ys), maxy = Math.max.apply(null, ys);
    var padx = Math.max((maxx - minx) * 0.18, 55), pady = Math.max((maxy - miny) * 0.18, 40);
    minx -= padx; maxx += padx; miny -= pady; maxy += pady;
    var cx = (minx + maxx) / 2, cy = (miny + maxy) / 2, w = maxx - minx, h = maxy - miny;
    if (w / h < AR) w = h * AR; else h = w / AR;
    var t = tighten || 0.85; w *= t; h *= t;   // tighten the continental frame (smaller = closer zoom)
    if (w > VB_W) { w = VB_W; h = w / AR; }
    if (h > VB_H) { h = VB_H; w = h * AR; }
    var x0 = Math.max(0, Math.min(VB_W - w, cx - w / 2));
    var y0 = Math.max(0, Math.min(VB_H - h, cy - h / 2));
    return [x0, y0, w, h];
  }

  function init() {
    var mount = document.querySelector(".cl-map-mount");
    if (!mount || mount.dataset.ready) return;
    mount.dataset.ready = "1";
    var backUrl = mount.getAttribute("data-back") || "Publications.html";

    // Preferred path: page-local globals (work over file:// and http).
    if (window.CL_MAP_DATA && window.CL_MAP_WORLD) {
      render(mount, window.CL_MAP_DATA, window.CL_MAP_WORLD, backUrl);
      return;
    }
    // Fallback: fetch (http only) when the mount points at JSON files instead.
    var locUrl = mount.getAttribute("data-locations");
    var worldUrl = mount.getAttribute("data-world");
    if (!locUrl || !worldUrl) {
      var m = el("p"); m.textContent = "Researcher-map data script did not load.";
      mount.appendChild(m); if (window.console) console.error("researcher-map: window.CL_MAP_DATA/CL_MAP_WORLD missing");
      return;
    }
    Promise.all([
      fetch(locUrl).then(function (r) { return r.json(); }),
      fetch(worldUrl).then(function (r) { return r.json(); })
    ]).then(function (res) {
      render(mount, res[0], res[1], backUrl);
    }).catch(function (err) {
      var p = el("p"); p.textContent = "Could not load the researcher-map data.";
      mount.appendChild(p); if (window.console) console.error("researcher-map:", err);
    });
  }

  function render(mount, data, world, backUrl) {
    var cities = (data.cities || []).slice();
    if (!cities.length) return;
    var maxc = cities.reduce(function (m, c) { return Math.max(m, c.count); }, 1);
    var reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

    var root = el("div", "cl-map");
    mount.appendChild(root);                 // connect first so .cl-map tokens (incl. slate theme) resolve
    var cs = getComputedStyle(root);

    /* ---- header ---- */
    var top = el("div", "cl-map-top");
    var lead = el("div", "lead");
    var located = data.located != null ? data.located : cities.reduce(function (s, c) { return s + c.count; }, 0);
    var total = data.total_researchers != null ? data.total_researchers : located;

    var eyebrow = el("p", "cl-map-eyebrow");
    var back = el("a", "back"); back.href = backUrl; back.textContent = "← Publications";
    eyebrow.appendChild(back);
    eyebrow.appendChild(document.createTextNode(" / where CosmoLattice is used "));
    var chip = el("span", "cl-map-methodchip"); chip.tabIndex = 0; chip.setAttribute("role", "note");
    chip.appendChild(document.createTextNode("ⓘ how it's counted"));
    var hint = el("span", "mhint");
    var hintHtml = "Built from INSPIRE‑HEP: each researcher is placed at the <b>first affiliation</b> listed " +
      "on their <b>most recent</b> “Using CL” paper and binned by city using INSPIRE's coordinates. A second " +
      "affiliation is ignored, and each person is shown once. <b>" + located + "</b> of <b>" + total + "</b> authors are located";
    if (data.unresolved_count) hintHtml += "; <b>" + data.unresolved_count + "</b> have no location on record";
    if (data.approx_placed_count) hintHtml += " and <b>" + data.approx_placed_count + "</b> sit at their city centre";
    hint.innerHTML = hintHtml + ".";
    chip.appendChild(hint); eyebrow.appendChild(chip);
    lead.appendChild(eyebrow);

    var title = el("h1", "cl-map-title"); title.textContent = located + " researchers, located";
    lead.appendChild(title);
    top.appendChild(lead);

    var stats = el("div", "cl-map-stats");
    [[located, "located"], [data.cities_count != null ? data.cities_count : cities.length, "cities"],
     [data.countries_count, "countries"], [data.papers, "papers"]].forEach(function (s) {
      if (s[0] == null) return;
      var d = el("div", "cl-map-stat");
      d.innerHTML = "<b>" + esc(String(s[0])) + "</b><span>" + esc(s[1]) + "</span>";
      stats.appendChild(d);
    });
    top.appendChild(stats);
    root.appendChild(top);

    /* ---- layout ---- */
    var grid = el("div", "cl-map-grid");
    var mapcol = el("div", "cl-map-mapcol");
    var tabbar = el("div", "cl-map-tabs"); tabbar.setAttribute("role", "tablist");
    tabbar.setAttribute("aria-label", "Zoom the map to a continent");
    mapcol.appendChild(tabbar);
    var frame = el("div", "cl-map-frame");
    var svg = svgEl("svg");
    var WORLD_VB = [145, 58, 1005, 412], WORLD_W = WORLD_VB[2];
    // World view crops to the populated band (≈ lon −137…+166, lat 72°N…−51°S)
    // so the continents fill the frame and empty polar/Pacific ocean is trimmed.
    svg.setAttribute("viewBox", WORLD_VB.join(" "));
    svg.setAttribute("role", "img");
    svg.setAttribute("aria-label", "World map of researcher locations, point size and glow by count");
    frame.appendChild(svg);
    mapcol.appendChild(frame);
    grid.appendChild(mapcol);

    var hubs = el("aside", "cl-map-hubs");
    grid.appendChild(hubs);
    root.appendChild(grid);

    /* ---- map layers ---- */
    var land = svgEl("path", "land"); land.setAttribute("d", world.path || ""); svg.appendChild(land);
    var grat = svgEl("g", "grat");
    var lon, lat, l;
    for (lon = -150; lon <= 150; lon += 30) { l = svgEl("line"); var px = proj(0, lon)[0];
      l.setAttribute("x1", px); l.setAttribute("y1", 0); l.setAttribute("x2", px); l.setAttribute("y2", VB_H); grat.appendChild(l); }
    for (lat = -60; lat <= 60; lat += 30) { l = svgEl("line"); var py = proj(lat, 0)[1];
      l.setAttribute("x1", 0); l.setAttribute("y1", py); l.setAttribute("x2", VB_W); l.setAttribute("y2", py); grat.appendChild(l); }
    svg.appendChild(grat);

    var glowG = svgEl("g"), coreG = svgEl("g", "reveal");
    svg.appendChild(glowG); svg.appendChild(coreG);

    var ptLo = cs.getPropertyValue("--clm-pt-lo").trim() || "#3f74a6";
    var ptHi = cs.getPropertyValue("--clm-pt-hi").trim() || "#8fd6ff";

    // World view labels the global top 10; a continent view can label every one
    // of its cities — declutter() then hides any whose text would overlap once
    // the frame is zoomed in.
    var worldLabel = {}, byCont = {};
    cities.slice().sort(function (a, b) { return b.count - a.count; }).slice(0, 10)
      .forEach(function (c) { worldLabel[c.city] = 1; });
    cities.forEach(function (c) { var k = continentOf(c); (byCont[k] = byCont[k] || []).push(c); });

    /* ---- city card ----
       Hover a marker to peek at the city and the papers written from it; click
       to pin the card, which lists every paper and turns the rows into arXiv
       links. The card anchors to the marker rather than the cursor — at this
       size a card that chases the pointer is unreadable, and a pinned card has
       to hold still to be clickable.

       The arXiv id column doubles as the date: papers come newest first, so the
       ids read as a descending timeline. A trailing numeral on a row is the
       number of authors from this city, shown only when it is more than one. */
    var papers = data.paper_list || [];
    var PEEK = 4;                              // papers listed on hover; the rest need a pin
    var tt = el("div", "cl-map-tt"); frame.appendChild(tt);
    var pinnedCity = null, pinnedNode = null;

    function paperRow(entry, linked) {
      var p = papers[entry[0]] || {}, id = p.arxiv || "";
      var inner = '<span class="id">' + esc(id) + "</span>" +
        '<span class="t">' + esc(demath(p.title)) + "</span>" +
        (entry[1] > 1 ? '<span class="n" title="' + entry[1] + ' authors from here">' + entry[1] + "</span>" : "");
      return (linked && id)
        ? '<a class="pp" href="https://arxiv.org/abs/' + esc(id) + '" target="_blank" rel="noopener">' + inner + "</a>"
        : '<div class="pp">' + inner + "</div>";
    }

    function cardHtml(c, full) {
      var list = c.papers || [], shown = full ? list : list.slice(0, PEEK);
      var h = '<div class="c"><span>' + esc(c.city) + '</span><span class="n">' + c.count + "</span></div>" +
        '<div class="co">' + esc(c.country || "") + " · researcher" + (c.count > 1 ? "s" : "") + "</div>";
      var inst = (c.institutions || []).slice(0, 3).join(" · ");
      if (inst) h += '<div class="inst">' + esc(inst) + "</div>";
      if (!list.length) return h;
      h += '<div class="ph"><span>papers from here</span><span>' + list.length + "</span></div>" +
        '<div class="pl">' + shown.map(function (e) { return paperRow(e, full); }).join("") + "</div>";
      var rest = list.length - shown.length;
      if (rest > 0) h += '<div class="more">+' + rest + " more · click the point to open</div>";
      else if (!full) h += '<div class="more">Click the point to open on arXiv</div>';
      return h;
    }

    function placeCard(node) {
      var fr = frame.getBoundingClientRect(), r = node.getBoundingClientRect();
      tt.style.maxHeight = (fr.height - 16) + "px";
      var card = tt.getBoundingClientRect(), w = card.width, h = card.height;
      var x = r.right - fr.left + 14;                       // to the right of the point…
      if (x + w > fr.width - 8) x = r.left - fr.left - w - 14;   // …unless it would overhang
      tt.style.left = Math.max(8, Math.min(fr.width - w - 8, x)) + "px";
      var y = r.top - fr.top + r.height / 2 - h / 2;        // vertically centred on the point
      tt.style.top = Math.max(8, Math.min(fr.height - h - 8, y)) + "px";
    }

    function showTip(c, node) {
      if (pinnedCity) return;                  // a pinned card owns the frame
      tt.innerHTML = cardHtml(c, false);
      tt.classList.add("on");
      placeCard(node);
    }
    function hideTip() { if (!pinnedCity) tt.classList.remove("on"); }

    // The frame is a wide, shallow band, so a long paper list has to scroll
    // inside the pinned card. Fade its bottom edge while there is more below,
    // since macOS hides the scrollbar until you touch it.
    var pinnedList = null;
    function markOverflow() {
      if (!pinnedList) return;
      tt.classList.toggle("fades", pinnedList.scrollHeight - pinnedList.clientHeight - pinnedList.scrollTop > 4);
    }

    function pinCity(c, node) {
      if (pinnedCity) unpin();
      pinnedCity = c; pinnedNode = node;
      tt.innerHTML = cardHtml(c, true);
      var x = el("button", "x"); x.type = "button";
      x.setAttribute("aria-label", "Close the " + c.city + " papers");
      x.innerHTML = "×";
      x.addEventListener("click", unpin);
      tt.appendChild(x);
      tt.classList.add("on", "pin");
      placeCard(node);
      pinnedList = tt.querySelector(".pl");
      if (pinnedList) pinnedList.addEventListener("scroll", markOverflow);
      markOverflow();
      placeCard(node);        // re-place: the list only takes its final height once capped
      focus(c.city, true);
    }
    function unpin() {
      if (!pinnedCity) return;
      var city = pinnedCity.city;
      pinnedCity = null; pinnedNode = null; pinnedList = null;
      tt.classList.remove("on", "pin", "fades");
      focus(city, false);
    }
    // A resize changes the frame, and with it where the card belongs.
    window.addEventListener("resize", function () {
      if (!pinnedNode) return;
      placeCard(pinnedNode);
      markOverflow();
    });
    // Dismiss: anywhere outside the card, or Escape.
    document.addEventListener("click", function (e) {
      if (pinnedCity && !tt.contains(e.target)) unpin();
    });
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape" || e.key === "Esc") unpin();
    });

    var nodes = [];
    function nodeOf(city) {
      for (var i = 0; i < nodes.length; i++) if (nodes[i].city === city) return nodes[i];
      return null;
    }
    function focus(city, on) {
      // Only cities visible in the current tab react; hovering a hub whose city
      // sits in another continent leaves the shown markers untouched.
      var vis = nodes.some(function (n) { return n.city === city && n.core.style.display !== "none"; });
      var act = on && vis;
      nodes.forEach(function (n) {
        if (n.core.style.display === "none") return;
        var active = n.city === city;
        n.core.classList.toggle("dim", act && !active);
        n.glow.style.opacity = act && !active ? "0.04" : "";
        n.core.style.transform = (active && act) ? "scale(1.55)" : "";
      });
      Array.prototype.forEach.call(hubs.querySelectorAll(".cl-map-hub"), function (h) {
        h.classList.toggle("hot", on && h.dataset.city === city);
      });
    }

    cities.forEach(function (c, i) {
      var p = proj(c.lat, c.lon), cx = p[0], cy = p[1];
      var t = c.count / maxc;
      var rc = 3 + Math.sqrt(c.count) * 1.15, rg = 8 + Math.sqrt(c.count) * 4.6;

      var glow = svgEl("circle", "glow");
      glow.setAttribute("cx", cx); glow.setAttribute("cy", cy); glow.setAttribute("r", rg);
      glow.setAttribute("opacity", (0.10 + 0.42 * t).toFixed(3));
      glowG.appendChild(glow);

      var hr = null;
      if (c.count === maxc) {
        hr = svgEl("circle", "hotring");
        hr.setAttribute("cx", cx); hr.setAttribute("cy", cy); hr.setAttribute("r", rc + 4.5);
        coreG.appendChild(hr);
      }

      var core = svgEl("circle", "core");
      core.setAttribute("cx", cx); core.setAttribute("cy", cy); core.setAttribute("r", rc);
      core.style.fill = mix(ptLo, ptHi, Math.pow(t, 0.7));
      core.style.transitionDelay = (i * 14) + "ms";
      coreG.appendChild(core);

      var left = cx > VB_W - 140;
      var tx = svgEl("text", "ptlabel");
      if (left) tx.setAttribute("text-anchor", "end");
      tx.textContent = c.city;
      tx.style.display = "none";      // shown per-view by applyView/declutter
      coreG.appendChild(tx);

      core.addEventListener("mouseenter", function () { showTip(c, core); focus(c.city, true); });
      core.addEventListener("mouseleave", function () {
        hideTip();
        if (pinnedCity) focus(pinnedCity.city, true); else focus(c.city, false);
      });
      core.addEventListener("click", function (e) {
        e.stopPropagation();
        if (pinnedCity === c) unpin(); else pinCity(c, core);
      });
      nodes.push({
        city: c.city, count: c.count, core: core, glow: glow, hotring: hr, label: tx,
        cont: continentOf(c), cx: cx, cy: cy, baseR: rc, baseRg: rg, labelLeft: left,
        labelWorld: !!worldLabel[c.city], labelHidden: false
      });
    });

    /* ---- legend ---- */
    var legend = el("div", "cl-map-legend");
    legend.innerHTML = '<span class="t">researchers<br>per city</span>';
    var lvals = [1, Math.max(2, Math.round(maxc / 3)), Math.max(3, Math.round(maxc * 2 / 3)), maxc];
    lvals.filter(function (v, i, a) { return a.indexOf(v) === i; }).forEach(function (v) {
      var d = 2 * (3 + Math.sqrt(v) * 1.15) * 0.9;
      var lg = el("div", "lg");
      lg.innerHTML = '<span class="d" style="width:' + d.toFixed(0) + "px;height:" + d.toFixed(0) + 'px"></span><span>' + v + "</span>";
      legend.appendChild(lg);
    });
    frame.appendChild(legend);

    /* ---- hub list ---- */
    hubs.innerHTML = '<h2>Leading hubs</h2><p class="note">Hover to link a row to its point; ' +
      "click for the papers.</p>";
    cities.slice().sort(function (a, b) { return b.count - a.count || a.city.localeCompare(b.city); })
      .slice(0, 12).forEach(function (c, i) {
      var b = el("button", "cl-map-hub"); b.type = "button"; b.dataset.city = c.city;
      b.innerHTML = '<span class="rk">' + (i + 1) + "</span>" +
        '<span class="nm">' + esc(c.city) + "<small>" + esc(c.country || "") + "</small></span>" +
        '<span class="val"><span class="bar"><i style="width:' + (c.count / maxc * 100) + '%"></i></span>' +
        '<span class="n">' + c.count + "</span></span>";
      b.addEventListener("mouseenter", function () { focus(c.city, true); });
      b.addEventListener("mouseleave", function () {
        if (pinnedCity) focus(pinnedCity.city, true); else focus(c.city, false);
      });
      // Rows are the keyboard route to the papers: the markers themselves are
      // not tab stops. A row for a city hidden by the current tab switches to
      // that continent first, so the pinned card always has its point on screen.
      b.addEventListener("click", function (e) {
        e.stopPropagation();
        var n = nodeOf(c.city);
        if (!n) return;
        if (pinnedCity === c) { unpin(); return; }
        if (n.core.style.display === "none") selectTab(n.cont, true);
        pinCity(c, n.core);
      });
      hubs.appendChild(b);
    });
    var foot = el("p", "foot"); foot.innerHTML = "Point size ∝ √(researchers); glow ∝ intensity.";
    hubs.appendChild(foot);

    /* ---- continent tabs (map switcher) ----
       World + one tab per populated continent. Clicking a tab zooms the map and
       shows only that continent's markers; the hubs list stays global. */
    var views = { world: WORLD_VB };
    var tabDefs = [{ key: "world", name: "World", n: located }];
    CONTS.forEach(function (ct) {
      var list = byCont[ct.key];
      if (!list || !list.length) return;
      views[ct.key] = computeVB(list, ct.key === "eu" ? 0.765 : 0.85);   // Europe zoomed a touch closer
      tabDefs.push({ key: ct.key, name: ct.name, n: list.reduce(function (s, c) { return s + c.count; }, 0) });
    });

    // Counter-scale marker/label geometry by the zoom factor so they keep a
    // constant on-screen size instead of ballooning as the viewBox shrinks.
    var LABEL_PX = 12;   // on-screen label size (native units at k = 1)
    function applyScale(w) {
      var k = w / WORLD_W;
      nodes.forEach(function (n) {
        n.core.setAttribute("r", (n.baseR * k).toFixed(2));
        n.glow.setAttribute("r", (n.baseRg * k).toFixed(2));
        if (n.hotring) n.hotring.setAttribute("r", ((n.baseR + 4.5) * k).toFixed(2));
        var off = (n.baseR + 4) * k;
        n.label.setAttribute("x", (n.labelLeft ? n.cx - off : n.cx + off).toFixed(2));
        n.label.setAttribute("y", (n.cy + LABEL_PX * 0.34 * k).toFixed(2));
        n.label.style.fontSize = (LABEL_PX * k).toFixed(2) + "px";
      });
    }

    // Greedy label collision removal in native coords for the target frame:
    // walk the labelled, visible cities by count and drop any whose text box
    // would overlap one already kept.
    function declutter(key, w) {
      var k = w / WORLD_W, fontN = LABEL_PX * k, charW = fontN * 0.62, pad = fontN * 0.3, placed = [];
      nodes.filter(function (n) {
        var vis = key === "world" || n.cont === key;
        return vis && (key === "world" ? n.labelWorld : true);
      }).sort(function (a, b) { return b.count - a.count; }).forEach(function (n) {
        var boxW = n.label.textContent.length * charW, off = (n.baseR + 4) * k;
        var x0 = n.labelLeft ? n.cx - off - boxW : n.cx + off, x1 = x0 + boxW;
        var y1 = n.cy + 3 * k, y0 = y1 - fontN;
        var r = { x0: x0 - pad, y0: y0 - pad, x1: x1 + pad, y1: y1 + pad };
        var hit = placed.some(function (p) { return !(r.x1 < p.x0 || r.x0 > p.x1 || r.y1 < p.y0 || r.y0 > p.y1); });
        n.labelHidden = hit;
        if (!hit) placed.push(r);
      });
    }

    function applyView(key) {
      nodes.forEach(function (n) {
        var vis = key === "world" || n.cont === key;
        var disp = vis ? "" : "none";
        n.glow.style.display = disp; n.core.style.display = disp;
        if (n.hotring) n.hotring.style.display = disp;
        var cand = vis && (key === "world" ? n.labelWorld : true);
        n.label.style.display = (cand && !n.labelHidden) ? "" : "none";
      });
    }

    var vbRAF = null;
    function setVB(target) {
      if (vbRAF) { cancelAnimationFrame(vbRAF); vbRAF = null; }
      if (reduce) {
        svg.setAttribute("viewBox", target.join(" ")); applyScale(target[2]);
        if (pinnedNode) placeCard(pinnedNode);
        return;
      }
      var cur = svg.getAttribute("viewBox").split(" ").map(Number), start = null;
      function step(ts) {
        if (start == null) start = ts;
        var p = Math.min(1, (ts - start) / 460);
        var e = p < 0.5 ? 2 * p * p : 1 - Math.pow(-2 * p + 2, 2) / 2; // easeInOutQuad
        var v = cur.map(function (c, i) { return c + (target[i] - c) * e; });
        svg.setAttribute("viewBox", v.map(function (x) { return x.toFixed(2); }).join(" "));
        applyScale(v[2]);
        if (pinnedNode) placeCard(pinnedNode);   // keep a pinned card glued to its point
        if (p < 1) vbRAF = requestAnimationFrame(step); else vbRAF = null;
      }
      vbRAF = requestAnimationFrame(step);
    }

    function selectTab(key, animate) {
      Array.prototype.forEach.call(tabbar.children, function (b) {
        b.setAttribute("aria-selected", b.dataset.key === key ? "true" : "false");
      });
      var vb = views[key];
      declutter(key, vb[2]);   // decide the visible label set for the target frame
      applyView(key);
      // A card left pinned to a point the new view hides would float unanchored.
      if (pinnedCity && !(key === "world" || (nodeOf(pinnedCity.city) || {}).cont === key)) unpin();
      if (animate) { setVB(vb); }
      else { svg.setAttribute("viewBox", vb.join(" ")); applyScale(vb[2]); }
    }

    tabDefs.forEach(function (d) {
      var b = el("button", "cl-map-tab"); b.type = "button"; b.dataset.key = d.key;
      b.setAttribute("role", "tab");
      b.innerHTML = esc(d.name) + '<span class="n">' + d.n + "</span>";
      b.addEventListener("click", function () { selectTab(d.key, true); });
      tabbar.appendChild(b);
    });
    selectTab("world", false);

    /* ---- reveal ---- */
    if (reduce) { coreG.classList.add("on"); }
    else { requestAnimationFrame(function () { requestAnimationFrame(function () { coreG.classList.add("on"); }); }); }
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
